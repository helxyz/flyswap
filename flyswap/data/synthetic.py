"""Synthetic connectome pairs with known ground truth.

The real datasets are gigabytes and need manual download, which makes them
useless for CI and slow for development. This module builds small male/female
connectome pairs that share the schema and, crucially, have a *known answer*:
a planted circuit whose sex difference is caused by named cell types.

That planted truth is what makes the tests meaningful. If the graft framework
cannot recover a difference we deliberately wired in, it will not recover a
real one. Two females are generated too (`female_a`, `female_b`), differing
only by sampling noise, so the variability baseline has something to measure.

Two design choices are worth explaining, because both were forced by bugs the
first version of this file hid:

**Every neuron needs several input sources.** Weights are normalised to input
*fraction*, so a neuron whose only input is one partner receives a share of
1.0 from it no matter how many synapses are involved. A planted weight
difference on such a neuron is invisible after normalisation. The `BKGD` type
projects broadly for exactly this reason, and real brains are densely
connected in the same way.

**Structure is shared; only weights vary between animals.** If each animal
redrew which pairs connect, the resulting structural noise would swamp any
planted signal in a graph this small. Matched cell types in real connectomes
connect to the same partners with quantitative variation, so the generator
fixes the sparsity pattern across animals and varies synapse counts.
"""

from __future__ import annotations

from dataclasses import dataclass

import numpy as np
import pandas as pd

from flyswap.data.schema import Connectome, DatasetSpec

#: Cell types in the toy brain. The chain sensory -> relay -> premotor ->
#: motor is isomorphic between sexes; the COURT/SONG types carry the planted
#: dimorphism. BKGD gives every neuron a second input source (see module doc).
TOY_TYPES = {
    "SENS": dict(n=12, superclass="sensory", nt="acetylcholine"),
    "RELAY": dict(n=10, superclass="intrinsic", nt="acetylcholine"),
    "INHIB": dict(n=6, superclass="intrinsic", nt="gaba"),
    "PREMOT": dict(n=8, superclass="descending", nt="acetylcholine"),
    "MOTOR": dict(n=4, superclass="motor", nt="acetylcholine"),
    "COURT_A": dict(n=6, superclass="intrinsic", nt="acetylcholine"),
    "COURT_B": dict(n=6, superclass="intrinsic", nt="acetylcholine"),
    "SONG": dict(n=4, superclass="descending", nt="acetylcholine"),
    "BKGD": dict(n=10, superclass="intrinsic", nt="acetylcholine"),
}

#: Shared by both sexes: (pre type, post type, mean synapse count).
ISOMORPHIC_EDGES = [
    ("SENS", "RELAY", 20.0),
    ("RELAY", "PREMOT", 18.0),
    ("PREMOT", "MOTOR", 25.0),
    ("RELAY", "INHIB", 12.0),
    ("INHIB", "PREMOT", 15.0),
    ("SENS", "COURT_A", 14.0),
    # Background input to every downstream population, so no neuron's input
    # share is pinned to 1.0 by having a single source.
    ("BKGD", "RELAY", 6.0),
    ("BKGD", "PREMOT", 6.0),
    ("BKGD", "MOTOR", 8.0),
    ("BKGD", "COURT_A", 6.0),
    ("BKGD", "COURT_B", 8.0),
    ("BKGD", "SONG", 8.0),
    ("BKGD", "INHIB", 6.0),
]

#: The planted sex difference. COURT_A -> COURT_B -> SONG is strong in the
#: male and weak in the female, so stimulating SENS should drive SONG in the
#: male only. COURT_B is the single type that carries the difference: it is
#: both the target of the strong input and the source of the strong output.
DIMORPHIC_EDGES = {
    "male": [("COURT_A", "COURT_B", 30.0), ("COURT_B", "SONG", 34.0)],
    "female": [("COURT_A", "COURT_B", 2.0), ("COURT_B", "SONG", 2.0)],
}

#: Ground truth the tests assert against.
PLANTED_DIMORPHIC_TYPES = ("COURT_B",)
PLANTED_READOUT = "SONG"
PLANTED_STIMULUS = "SENS"
#: A readout that should NOT differ between sexes, used as a negative control.
PLANTED_NULL_READOUT = "MOTOR"

#: Seed for the connection pattern, shared by every animal.
STRUCTURE_SEED = 20261015


@dataclass
class SyntheticPair:
    male: Connectome
    female_a: Connectome
    female_b: Connectome

    def as_dict(self) -> dict[str, Connectome]:
        return {
            "male": self.male,
            "female_a": self.female_a,
            "female_b": self.female_b,
        }


def _spec(name: str, sex: str) -> DatasetSpec:
    return DatasetSpec(
        name=name,
        sex=sex,  # type: ignore[arg-type]
        regions=("brain", "vnc"),
        citation="Synthetic data generated by flyswap.data.synthetic; not real.",
        download="n/a",
    )


def _build_neurons(side_split: bool) -> tuple[pd.DataFrame, dict]:
    """Neuron table and a {(type, side): [body_id, ...]} index.

    Built from a fixed layout so every animal has the same cell inventory,
    which is what lets types be matched across them.
    """
    rows = []
    members: dict[tuple[str, str], list[int]] = {}
    body_id = 1
    for type_name, cfg in TOY_TYPES.items():
        sides = ["L", "R"] if side_split else ["M"]
        per_side = max(1, cfg["n"] // len(sides))
        for side in sides:
            ids = []
            for _ in range(per_side):
                rows.append(
                    {
                        "body_id": body_id,
                        "cell_type": type_name,
                        "side": side,
                        "superclass": cfg["superclass"],
                        "nt": cfg["nt"],
                        "nt_conf": 0.95,
                        "fru_dsx": "fru" if type_name.startswith("COURT") else "none",
                    }
                )
                ids.append(body_id)
                body_id += 1
            members[(type_name, side)] = ids
    return pd.DataFrame(rows), members


def make_connectome(
    name: str,
    sex: str,
    seed: int = 0,
    density_factor: float = 1.0,
    noise: float = 0.12,
    side_split: bool = True,
    connect_prob: float = 0.6,
) -> Connectome:
    """Build one toy connectome.

    `density_factor` scales every synapse count, mimicking the reconstruction
    difference between real datasets (male neurons carry roughly 1.8x the
    synapses of their female counterparts). Input-fraction normalisation must
    cancel it, and a test checks that it does.

    `seed` varies only the synapse counts. The connection *pattern* is fixed
    by `STRUCTURE_SEED` so that animals are comparable.
    """
    structure_rng = np.random.default_rng(STRUCTURE_SEED)
    weight_rng = np.random.default_rng(seed)

    neurons, members = _build_neurons(side_split)
    sides = ["L", "R"] if side_split else ["M"]

    edge_rows: list[dict] = []
    for pre_type, post_type, mean_count in ISOMORPHIC_EDGES + DIMORPHIC_EDGES[sex]:
        for side in sides:
            for p in members[(pre_type, side)]:
                for q in members[(post_type, side)]:
                    # Sparsity from the shared structure stream: the same
                    # pairs connect in every animal.
                    if structure_rng.random() > connect_prob:
                        continue
                    scale = mean_count * density_factor
                    count = weight_rng.normal(scale, scale * noise)
                    edge_rows.append(
                        {"pre": p, "post": q, "count": int(max(1, round(count)))}
                    )

    edges = pd.DataFrame(edge_rows).groupby(
        ["pre", "post"], as_index=False
    )["count"].sum()

    conn = Connectome(
        spec=_spec(name, sex),
        neurons=neurons,
        edges=edges,
        provenance={
            "synthetic": True,
            "seed": seed,
            "structure_seed": STRUCTURE_SEED,
            "density_factor": density_factor,
            "noise": noise,
            "planted_dimorphic_types": list(PLANTED_DIMORPHIC_TYPES),
            "planted_readout": PLANTED_READOUT,
            "planted_null_readout": PLANTED_NULL_READOUT,
        },
    )
    conn.validate()
    return conn


def make_pair(seed: int = 0, male_density: float = 1.8) -> SyntheticPair:
    """A male and two females, with the male denser by `male_density`.

    The two females differ only in their weight-noise seed, so any male-female
    difference that counts as real must exceed the female-female difference.
    """
    return SyntheticPair(
        male=make_connectome(
            "synthetic_male", "male", seed=seed, density_factor=male_density
        ),
        female_a=make_connectome("synthetic_female_a", "female", seed=seed + 100),
        female_b=make_connectome("synthetic_female_b", "female", seed=seed + 200),
    )
